"""Build portable MariaDB SQL from registered migrations and the catalog seed.

No connection, credentials, local database dump or user records are needed.
The checked-in full file targets the same demo database as Docker Compose.
"""
import argparse
from pathlib import Path
import re

from seed_demo_catalog import sql_rows
from tv3_schema import MIGRATION_RANGE, ROOT, migration_paths

DEFAULT_DATABASE = "furniture_shop_tv3_dev"
OUTPUT_DIRECTORY = ROOT / "docs/database/demo"
FULL_FILENAME = "TV2_FULL_DATABASE_DEMO.sql"
DATA_FILENAME = "TV2_CATALOG_DATA.sql"


def database_name(value):
    if not re.fullmatch(r"furniture_shop(?:_tv3_dev|_test_[a-z0-9_]+)?", value):
        raise ValueError("Use furniture_shop, furniture_shop_tv3_dev or furniture_shop_test_*.")
    return value


def schema_sql(database=DEFAULT_DATABASE):
    database_name(database)
    parts = [
        "-- GENERATED by python scripts/build_tv2_catalog_sql.py; MariaDB 12.2 / UTF-8.",
        f"-- Full {MIGRATION_RANGE} schema. Import into a NEW database; stop on the first error.",
        "-- Existing database: use migrations and TV2_CATALOG_DATA.sql instead.",
        "-- No DROP/TRUNCATE, credentials, users, orders or payment data are exported.",
    ]
    for position, path in enumerate(migration_paths()):
        sql = path.read_text(encoding="utf-8")
        if position == 0:
            sql = sql.replace("CREATE DATABASE furniture_shop CHARACTER", f"CREATE DATABASE `{database}` CHARACTER", 1)
            sql = sql.replace("USE furniture_shop;", f"USE `{database}`;", 1)
        parts.extend((f"\n-- BEGIN {path.name}", sql.rstrip(), f"-- END {path.name}"))
    return "\n".join(parts) + "\n"


def data_sql():
    return "\n".join((
        "-- GENERATED by python scripts/build_tv2_catalog_sql.py; MariaDB 12.2 / UTF-8.",
        "-- Select your furniture database with the complete V001-V015 schema first.",
        "-- 50 demo products / 150 SKUs, 3 SKUs per product, images, taxonomy and initial stock.",
        "-- Existing SKU IDs, prices, statuses and inventory are retained on rerun.",
        "-- Each seed increases demo product versions and queues pending vector synchronization.",
        "-- Run the whole file in ONE connection; stop on errors and ROLLBACK on failure.",
        "-- No user accounts/passwords, orders or personal data. Images live in the repository.",
        "SET NAMES utf8mb4;",
        "SET SESSION time_zone = '+00:00';",
        sql_rows(),
        "",
    ))


def full_sql(database=DEFAULT_DATABASE):
    return schema_sql(database) + "\n-- BEGIN demo catalog data\n" + data_sql()


def artifacts(database=DEFAULT_DATABASE):
    return {FULL_FILENAME: full_sql(database), DATA_FILENAME: data_sql()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=database_name, default=DEFAULT_DATABASE)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIRECTORY)
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ; do not write.")
    args = parser.parse_args()
    expected = artifacts(args.database)
    if args.check:
        stale = [name for name, content in expected.items()
                 if not (args.output_dir / name).is_file()
                 or (args.output_dir / name).read_text(encoding="utf-8") != content]
        if stale:
            parser.exit(1, "SQL artifacts are outdated; run python scripts/build_tv2_catalog_sql.py.\n")
        print("Verified SQL artifacts: registered schema and 50 products / 150 SKUs.")
        return
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in expected.items():
        (args.output_dir / name).write_text(content, encoding="utf-8", newline="\n")
    print("Generated TV2_FULL_DATABASE_DEMO.sql and TV2_CATALOG_DATA.sql (50 products / 150 SKUs).")


if __name__ == "__main__":
    main()
